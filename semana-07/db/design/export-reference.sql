-- Referencia para comparar la exportación PostgreSQL de la herramienta visual.
-- NO ejecutar en aula_web: su estructura se crea mediante las migraciones.
-- El exportador puede utilizar SERIAL en lugar de IDENTITY; revisar el resultado.
CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE
);
CREATE TABLE tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  title TEXT NOT NULL CHECK (length(trim(title)) > 0),
  done BOOLEAN NOT NULL DEFAULT FALSE,
  internal_note TEXT NOT NULL DEFAULT ''
);
-- DBML incluye el CHECK como nota: una nota no genera una restricción SQL.
-- Por eso la revisión del SQL exportado es parte del paso diseño -> migración.
